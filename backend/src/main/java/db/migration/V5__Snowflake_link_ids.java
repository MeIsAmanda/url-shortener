package db.migration;

import java.math.BigInteger;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.Instant;
import org.flywaydb.core.api.migration.BaseJavaMigration;
import org.flywaydb.core.api.migration.Context;

/** Freeze the historic Base62 alphabet and epoch here; preserve all saved aliases. */
public class V5__Snowflake_link_ids extends BaseJavaMigration {
    private static final String ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
    private static final long EPOCH = Instant.parse("2026-10-24T16:00:00Z").toEpochMilli();

    @Override
    public void migrate(Context context) throws SQLException {
        var connection = context.getConnection();
        long floor = 0;
        try (var query = connection.createStatement();
                var rows = query.executeQuery("SELECT id, code FROM short_links")) {
            while (rows.next()) {
                floor = Math.max(floor, rows.getLong("id"));
                floor = Math.max(floor, decode(rows.getString("code")));
            }
        }
        try (var query = connection.createStatement();
                ResultSet sequence = query.executeQuery("SELECT BASE_VALUE FROM INFORMATION_SCHEMA.SEQUENCES "
                        + "WHERE SEQUENCE_SCHEMA=CURRENT_SCHEMA AND SEQUENCE_NAME='SHORT_LINK_ID_SEQ'")) {
            if (!sequence.next()) throw new SQLException("Missing legacy sequence.");
            long next = sequence.getLong(1);
            if (sequence.wasNull()) throw new SQLException("The legacy ID space is exhausted.");
            floor = Math.max(floor, next - 1);
        }
        if (floor >>> 22 == (1L << 41) - 1) {
            throw new SQLException("No complete Snowflake timestamp remains above existing IDs and aliases.");
        }
        try (var ddl = connection.createStatement()) {
            ddl.execute("CREATE TABLE snowflake_settings (id INTEGER PRIMARY KEY CHECK (id=1), "
                    + "epoch_millis BIGINT NOT NULL, legacy_id_floor BIGINT NOT NULL)");
            ddl.execute("CREATE TABLE snowflake_workers (worker_id INTEGER PRIMARY KEY "
                    + "CHECK (worker_id BETWEEN 0 AND 1023), reserved_until_millis BIGINT NOT NULL)");
            ddl.execute("INSERT INTO snowflake_settings VALUES (1, " + EPOCH + ", " + floor + ")");
            ddl.execute("INSERT INTO snowflake_workers SELECT X, -1 FROM SYSTEM_RANGE(0, 1023)");
        }
        // Retain the old sequence as historical state; the production allocator no longer uses it.
    }

    private static long decode(String code) throws SQLException {
        if (code == null || !code.matches("[A-Za-z0-9]{1,11}")) {
            throw new SQLException("Unexpected legacy short-code format.");
        }
        BigInteger number = BigInteger.ZERO;
        for (char character : code.toCharArray()) {
            number = number.multiply(BigInteger.valueOf(62)).add(BigInteger.valueOf(ALPHABET.indexOf(character)));
        }
        // A value outside positive-long space can never be generated by our encoder.
        return number.compareTo(BigInteger.valueOf(Long.MAX_VALUE)) > 0 ? 0 : number.longValueExact();
    }
}
