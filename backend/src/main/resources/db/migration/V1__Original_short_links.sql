-- Matches the original Hibernate-created schema. IF NOT EXISTS adopts existing
-- development data after baselining at version 0, without replacing its rows.
CREATE TABLE IF NOT EXISTS short_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(7) NOT NULL,
    original_url VARCHAR(4096) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_short_link_code UNIQUE (code)
);
