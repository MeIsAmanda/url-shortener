package com.amanda.urlshortener.link;

import java.nio.file.Path;
import java.sql.Connection;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.dao.DataAccessException;
import static org.junit.jupiter.api.Assertions.*;

class SequenceMigrationTest {
    @TempDir Path directory;

    private DriverManagerDataSource dataSource(String name) {
        return new DriverManagerDataSource("jdbc:h2:file:"
                + directory.resolve(name).toAbsolutePath().toString().replace('\\', '/'), "sa", "");
    }

    private void migrate(DriverManagerDataSource source) {
        Flyway.configure().dataSource(source).locations("classpath:db/migration")
            .baselineOnMigrate(true).baselineVersion("0").load().migrate();
    }

    private void originalSchema(JdbcTemplate jdbc) {
        jdbc.execute("CREATE TABLE short_links (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "code VARCHAR(7) NOT NULL, original_url VARCHAR(4096) NOT NULL, "
                + "created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL, "
                + "CONSTRAINT uk_short_link_code UNIQUE(code))");
    }

    @Test
    void snowflakeUpgradeReservesAllOldAliasesAndKeepsExistingMetadata() {
        var source = dataSource("snowflake-upgrade");
        Flyway.configure().dataSource(source).locations("classpath:db/migration").target("4").load().migrate();
        var jdbc = new JdbcTemplate(source);
        jdbc.update("INSERT INTO user_accounts(google_subject, display_name, created_at) VALUES ('owner', 'Amanda', CURRENT_TIMESTAMP)");
        Long owner = jdbc.queryForObject("SELECT id FROM user_accounts WHERE google_subject='owner'", Long.class);
        long occupiedCodeId = (2000L << 22) | 123;
        String alias = new Base62Encoder().encode(occupiedCodeId);
        jdbc.update("INSERT INTO short_links(id, code, original_url, created_at, owner_id, click_count) "
                + "VALUES (10, ?, 'https://example.com/old', CURRENT_TIMESTAMP, ?, 7)", alias, owner);
        jdbc.update("INSERT INTO short_links(id, code, original_url, created_at) "
                + "VALUES (11, '0000001', 'https://example.com/leading-zero', CURRENT_TIMESTAMP)");
        jdbc.execute("ALTER SEQUENCE short_link_id_seq RESTART WITH 1000000");
        migrate(source);
        assertEquals(occupiedCodeId, jdbc.queryForObject("SELECT legacy_id_floor FROM snowflake_settings", Long.class));
        assertEquals(SnowflakeLinkIdAllocator.EPOCH_MILLIS, jdbc.queryForObject("SELECT epoch_millis FROM snowflake_settings", Long.class));
        assertEquals(1024L, jdbc.queryForObject("SELECT COUNT(*) FROM snowflake_workers", Long.class));
        assertEquals(owner, jdbc.queryForObject("SELECT owner_id FROM short_links WHERE code=?", Long.class, alias));
        assertEquals(7L, jdbc.queryForObject("SELECT click_count FROM short_links WHERE code=?", Long.class, alias));
        var clock = new SnowflakeLinkIdAllocatorTest.MutableClock(2000);
        var store = new SnowflakeTimestampStore(jdbc);
        var generator = new SnowflakeLinkIdAllocator(store, 0, clock, () -> clock.elapsed++);
        long newId = generator.nextId();
        assertTrue(newId > occupiedCodeId);
        assertNotEquals(alias, new Base62Encoder().encode(newId));
        var reopened = new JdbcTemplate(dataSource("snowflake-upgrade"));
        assertEquals(3000L, reopened.queryForObject("SELECT reserved_until_millis FROM snowflake_workers WHERE worker_id=0", Long.class));
        assertEquals("https://example.com/old", reopened.queryForObject("SELECT original_url FROM short_links WHERE code=?", String.class, alias));
        assertEquals("https://example.com/leading-zero", reopened.queryForObject("SELECT original_url FROM short_links WHERE code='0000001'", String.class));
    }

    @Test
    void snowflakeFloorAlsoIncludesAllocatedButUninsertedSequenceIds() {
        var source = dataSource("consumed-range");
        Flyway.configure().dataSource(source).locations("classpath:db/migration").target("4").load().migrate();
        var jdbc = new JdbcTemplate(source);
        jdbc.execute("ALTER SEQUENCE short_link_id_seq RESTART WITH 9000000000");
        migrate(source);
        assertEquals(8_999_999_999L, jdbc.queryForObject("SELECT legacy_id_floor FROM snowflake_settings", Long.class));
        assertEquals(9_000_000_000L, new DatabaseLinkIdAllocator(jdbc).nextId());
    }

    @Test
    void snowflakeMigrationRejectsAnExhaustedLegacyRangeWithoutChangingItsMapping() {
        var source = dataSource("snowflake-exhausted");
        Flyway.configure().dataSource(source).locations("classpath:db/migration").target("4").load().migrate();
        var jdbc = new JdbcTemplate(source);
        jdbc.update("INSERT INTO short_links(id, code, original_url, created_at) "
                + "VALUES (?, 'AzL8n0Y58m7', 'https://example.com/last', CURRENT_TIMESTAMP)", Long.MAX_VALUE);
        assertThrows(org.flywaydb.core.api.FlywayException.class, () -> migrate(source));
        assertEquals("https://example.com/last", jdbc.queryForObject("SELECT original_url FROM short_links WHERE id=?", String.class, Long.MAX_VALUE));
    }

    @Test
    void freshDatabaseStartsAtOneAndStartupDoesNotResetTheSequence() {
        var source = dataSource("fresh");
        migrate(source);
        assertEquals(1L, new DatabaseLinkIdAllocator(new JdbcTemplate(source)).nextId());
        // Unpooled connections close the file database. Reopen it and rerun
        // migration discovery to verify durable sequence state.
        var reopened = dataSource("fresh");
        migrate(reopened);
        assertEquals(2L, new DatabaseLinkIdAllocator(new JdbcTemplate(reopened)).nextId());
    }

    @Test
    void accountUpgradePreservesLegacyAliasesAndPersistsOwnersAndCounters() {
        var source = dataSource("account-upgrade");
        Flyway.configure().dataSource(source).locations("classpath:db/migration").target("3").load().migrate();
        var jdbc = new JdbcTemplate(source);
        long oldId = new DatabaseLinkIdAllocator(jdbc).nextId();
        String oldDestination = "https://example.com/" + "a".repeat(5000);
        jdbc.update("INSERT INTO short_links(id, code, original_url, created_at) VALUES (?, ?, ?, CURRENT_TIMESTAMP)",
                oldId, "legacy1", oldDestination);
        migrate(source);
        assertEquals(oldDestination, jdbc.queryForObject("SELECT original_url FROM short_links WHERE code='legacy1'", String.class));
        assertNull(jdbc.queryForObject("SELECT owner_id FROM short_links WHERE code='legacy1'", Long.class));
        assertEquals(0L, jdbc.queryForObject("SELECT click_count FROM short_links WHERE code='legacy1'", Long.class));
        jdbc.update("INSERT INTO user_accounts(google_subject, display_name, email, created_at) VALUES ('google-owner', 'Amanda', 'amanda@example.com', CURRENT_TIMESTAMP)");
        Long owner = jdbc.queryForObject("SELECT id FROM user_accounts WHERE google_subject='google-owner'", Long.class);
        long newId = new DatabaseLinkIdAllocator(jdbc).nextId();
        jdbc.update("INSERT INTO short_links(id, code, original_url, created_at, owner_id) VALUES (?, ?, ?, CURRENT_TIMESTAMP, ?)",
                newId, "owned1", "https://example.com/new", owner);
        jdbc.update("UPDATE short_links SET click_count=click_count+3 WHERE code='owned1'");
        var reopened = dataSource("account-upgrade");
        migrate(reopened);
        var restored = new JdbcTemplate(reopened);
        assertEquals(owner, restored.queryForObject("SELECT owner_id FROM short_links WHERE code='owned1'", Long.class));
        assertEquals(3L, restored.queryForObject("SELECT click_count FROM short_links WHERE code='owned1'", Long.class));
        assertEquals(1L, restored.queryForObject("SELECT COUNT(*) FROM user_accounts", Long.class));
        assertTrue(new DatabaseLinkIdAllocator(restored).nextId() > newId);
        assertThrows(DataAccessException.class, () -> restored.update("UPDATE short_links SET owner_id=-1 WHERE code='owned1'"));
    }

    @Test
    void preservesLegacyDataAndReservesItsCodeSpaceAcrossRestarts() {
        var source = dataSource("legacy");
        var jdbc = new JdbcTemplate(source);
        originalSchema(jdbc);
        String original = "https://example.com/legacy?x=1#section";
        jdbc.update("INSERT INTO short_links (id, code, original_url, created_at) VALUES (?, ?, ?, CURRENT_TIMESTAMP)",
                5L, "zzzzzzz", original);
        migrate(source);
        long id = new DatabaseLinkIdAllocator(jdbc).nextId();
        assertEquals(3_521_614_606_208L, id);
        String code = new Base62Encoder().encode(id);
        assertEquals("10000000", code);
        jdbc.update("INSERT INTO short_links (id, code, original_url, created_at) VALUES (?, ?, ?, CURRENT_TIMESTAMP)",
                id, code, "https://example.com/new");

        var reopened = dataSource("legacy");
        migrate(reopened);
        var reopenedJdbc = new JdbcTemplate(reopened);
        assertEquals(original, reopenedJdbc.queryForObject("SELECT original_url FROM short_links WHERE code = 'zzzzzzz'", String.class));
        assertEquals("https://example.com/new", reopenedJdbc.queryForObject("SELECT original_url FROM short_links WHERE code = ?", String.class, code));
        assertTrue(new DatabaseLinkIdAllocator(reopenedJdbc).nextId() > id);
        assertEquals(2L, reopenedJdbc.queryForObject("SELECT COUNT(*) FROM short_links", Long.class));
    }

    @Test
    void alsoReservesExistingPrimaryKeysWhenTheyExceedDecodedCodes() {
        var source = dataSource("large-primary-key");
        var jdbc = new JdbcTemplate(source);
        originalSchema(jdbc);
        jdbc.update("INSERT INTO short_links (id, code, original_url, created_at) VALUES (?, ?, ?, CURRENT_TIMESTAMP)",
                1_000_000L, "0000001", "https://example.com/old");
        migrate(source);
        assertEquals(1_000_001L, new DatabaseLinkIdAllocator(jdbc).nextId());
    }

    @Test
    void rolledBackAllocationsAreNotReissued() throws Exception {
        var source = dataSource("rollback");
        migrate(source);
        long allocated;
        try (Connection connection = source.getConnection()) {
            connection.setAutoCommit(false);
            try (var statement = connection.createStatement();
                    var result = statement.executeQuery("SELECT NEXT VALUE FOR short_link_id_seq")) {
                assertTrue(result.next());
                allocated = result.getLong(1);
            }
            connection.rollback();
        }
        assertTrue(new DatabaseLinkIdAllocator(new JdbcTemplate(source)).nextId() > allocated);
    }

    @Test
    void exhaustedSequenceFailsInsteadOfWrappingAndReusingIds() {
        var source = dataSource("exhausted");
        migrate(source);
        var jdbc = new JdbcTemplate(source);
        jdbc.execute("ALTER SEQUENCE short_link_id_seq RESTART WITH " + Long.MAX_VALUE);
        var allocator = new DatabaseLinkIdAllocator(jdbc);
        assertEquals(Long.MAX_VALUE, allocator.nextId());
        assertThrows(DataAccessException.class, allocator::nextId);
    }
}
